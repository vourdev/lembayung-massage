export function initI18n() {
  let currentLang = localStorage.getItem('lembayung_lang') || 'en';

  const updateUI = (lang) => {
    currentLang = lang;
    localStorage.setItem('lembayung_lang', lang);
    document.documentElement.lang = lang;

    const dict = translations[lang] || translations.en;

    document.querySelectorAll('[data-i18n]').forEach((el) => {
      const key = el.dataset.i18n;
      if (dict[key]) el.textContent = dict[key];
    });

    document.querySelectorAll('[data-lang-toggle]').forEach((btn) => {
      btn.textContent = dict.langBtn;
      btn.setAttribute('aria-label', lang === 'en' ? 'Ganti ke Bahasa Indonesia' : 'Switch to English');
    });
  };

  document.querySelectorAll('[data-lang-toggle]').forEach((btn) => {
    btn.addEventListener('click', () => {
      const nextLang = currentLang === 'en' ? 'id' : 'en';
      updateUI(nextLang);
    });
  });

  if (currentLang !== 'en') {
    updateUI(currentLang);
  }
}
